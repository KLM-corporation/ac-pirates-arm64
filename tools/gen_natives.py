"""Generates src/jni/natives_gen.cpp: host trampolines for every Java native
method declared in the APK's dex code.

Each trampoline forwards a Java -> native call to the guest implementation,
which is either an exported Java_* symbol of the ARM32 library or a function
registered at runtime through RegisterNatives.

usage: gen_natives.py <out.cpp> <arm32 lib.so> <dexdump.txt>...
"""
import re
import sys

from elftools.elf.elffile import ELFFile

HOST_TYPES = {"Z": "jboolean", "B": "jbyte", "C": "jchar", "S": "jshort", "I": "jint",
              "J": "jlong", "F": "jfloat", "D": "jdouble", "L": "jobject", "V": "void"}


def parse_sig(sig):
    args, i = [], 1
    while sig[i] != ")":
        c = sig[i]
        if c == "[":
            while sig[i] == "[":
                i += 1
            if sig[i] == "L":
                i = sig.index(";", i)
            i += 1
            args.append("L")
        elif c == "L":
            i = sig.index(";", i) + 1
            args.append("L")
        else:
            args.append(c)
            i += 1
    ret = sig[i + 1]
    return args, ("L" if ret == "[" else ret)


def mangle(s):
    out = []
    for ch in s:
        if ch.isascii() and ch.isalnum():
            out.append(ch)
        elif ch == "/":
            out.append("_")
        elif ch == "_":
            out.append("_1")
        elif ch == ";":
            out.append("_2")
        elif ch == "[":
            out.append("_3")
        else:
            out.append("_0%04x" % ord(ch))
    return "".join(out)


def read_natives(paths):
    natives, seen = [], set()
    for path in paths:
        cls = name = typ = None
        for line in open(path, encoding="utf-8", errors="replace"):
            m = re.match(r"\s+Class descriptor\s+:\s+'L(.*);'", line)
            if m:
                cls = m.group(1)
                continue
            m = re.match(r"\s+name\s+:\s+'(.*)'", line)
            if m:
                name = m.group(1)
                continue
            m = re.match(r"\s+type\s+:\s+'(.*)'", line)
            if m:
                typ = m.group(1)
                continue
            m = re.match(r"\s+access\s+:\s+0x([0-9a-f]+)\s+\((.*)\)", line)
            if m and "NATIVE" in m.group(2) and (cls, name, typ) not in seen:
                seen.add((cls, name, typ))
                natives.append((cls, name, typ))
    return natives


def elf_exports(path):
    with open(path, "rb") as f:
        elf = ELFFile(f)
        dynsym = elf.get_section_by_name(".dynsym")
        return {s.name for s in dynsym.iter_symbols() if s.name.startswith("Java_") and s["st_shndx"] != "SHN_UNDEF"}


def main():
    out_path, lib, dumps = sys.argv[1], sys.argv[2], sys.argv[3:]
    natives = read_natives(dumps)
    exports = elf_exports(lib)
    o = ["// Generated by tools/gen_natives.py. Do not edit.",
         "#include <jni.h>", "", '#include "../cpu.h"', '#include "../elf_loader.h"', '#include "jni_bridge.h"', "",
         "namespace {", "",
         "float as_float(zb::u64 r) { zb::u32 b = static_cast<zb::u32>(r); float f; memcpy(&f, &b, 4); return f; }",
         "double as_double(zb::u64 r) { double d; memcpy(&d, &r, 8); return d; }",
         "void missing(const char* what) { ZLOGE(\"Java called native %s, which the game never registered\", what); }",
         ""]
    exported = []
    for i, (cls, name, sig) in enumerate(natives):
        args, ret = parse_sig(sig)
        params = ", ".join(["JNIEnv* env", "jobject self"] + [f"{HOST_TYPES[t]} a{k}" for k, t in enumerate(args)])
        rtype = HOST_TYPES[ret]
        what = f"{cls}.{name}{sig}"
        o.append(f"zb::gaddr s_slot_{i} = 0;")
        o.append(f"{rtype} JNICALL nat_{i}({params}) {{")
        o.append(f"    if (!s_slot_{i}) {{ missing(\"{what}\"); return{'' if ret == 'V' else ' {}'}; }}")
        o.append("    zb::jni::NativeFrame f(env);")
        o.append("    zb::cpu::Args a;")
        o.append("    a.u32v(f.genv()).u32v(f.local(self));")
        for k, t in enumerate(args):
            o.append({
                "Z": f"    a.u32v(a{k} ? 1u : 0u);",
                "B": f"    a.i32v(a{k});", "S": f"    a.i32v(a{k});", "I": f"    a.i32v(a{k});",
                "C": f"    a.u32v(a{k});",
                "J": f"    a.u64v(static_cast<zb::u64>(a{k}));",
                "F": f"    a.f32v(a{k});", "D": f"    a.f64v(a{k});",
                "L": f"    a.u32v(f.local(a{k}));",
            }[t])
        call = f"zb::cpu::call(s_slot_{i}, a)"
        o.append({
            "V": f"    {call};",
            "Z": f"    return static_cast<jboolean>({call} & 0xFF);",
            "B": f"    return static_cast<jbyte>({call});",
            "C": f"    return static_cast<jchar>({call});",
            "S": f"    return static_cast<jshort>({call});",
            "I": f"    return static_cast<jint>(static_cast<zb::u32>({call}));",
            "J": f"    return static_cast<jlong>({call});",
            "F": f"    return as_float({call});",
            "D": f"    return as_double({call});",
            "L": f"    return zb::jni::to_host(static_cast<zb::u32>({call}));",
        }[ret])
        o.append("}")
        o.append("")
        sym = "Java_" + mangle(cls) + "_" + mangle(name)
        if sym in exports:
            exported.append((i, sym, args, ret, params))
    o.append("const zb::jni::NativeEntry kNatives[] = {")
    for i, (cls, name, sig) in enumerate(natives):
        o.append(f'    {{"{cls}", "{name}", "{sig}", reinterpret_cast<void*>(&nat_{i}), &s_slot_{i}}},')
    o.append("};")
    o.append("")
    o.append("}  // namespace")
    o.append("")
    for i, sym, args, ret, params in exported:
        argnames = ", ".join(["env", "self"] + [f"a{k}" for k in range(len(args))])
        o.append(f'extern "C" JNIEXPORT {HOST_TYPES[ret]} JNICALL {sym}({params}) {{ return nat_{i}({argnames}); }}')
    o.append("")
    o.append("namespace zb::jni {")
    o.append("")
    o.append("void register_generated_natives() {")
    for i, sym, *_ in exported:
        o.append(f'    s_slot_{i} = zb::elf::lookup("{sym}");')
    o.append("    set_native_table(kNatives, sizeof(kNatives) / sizeof(kNatives[0]));")
    o.append("}")
    o.append("")
    o.append("}  // namespace zb::jni")
    o.append("")
    with open(out_path, "w", newline="\n") as f:
        f.write("\n".join(o))
    missing = exports - {sym for _, sym, *_ in exported}
    print(f"{len(natives)} native declarations, {len(exported)} exported by the library")
    if missing:
        print("exports without a dex declaration:", sorted(missing))


if __name__ == "__main__":
    main()
